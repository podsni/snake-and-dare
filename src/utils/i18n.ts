export function t(lang: Lang, key: CopyKey, vars?: Record<string, string | number>): string {
  const template: string = M[key][lang]
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''))
}

export function faceLabel(lang: Lang, id: string): string {
  return FACES[id]?.[lang] ?? id
}

export function colorLabel(lang: Lang, hex: string): string {
  return COLORS[hex]?.[lang] ?? hex
}
